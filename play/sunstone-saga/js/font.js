// Draw text at (x,y). 8px per character cell. Uppercases automatically.
function drawText(ctx, str, x, y, color) {
  ctx.fillStyle = color || "#fcfcfc";
  str = String(str).toUpperCase();
  for (let i = 0; i < str.length; i++) {
    const g = FONT[str[i]] || FONT["?"];
    const gx = x + i * 8;
    for (let r = 0; r < 7; r++) {
      const row = g[r];
      for (let c = 0; c < 5; c++) {
        if (row[c] === "1") ctx.fillRect(gx + c + 1, y + r, 1, 1);
      }
    }
  }
}
function textW(str) { return String(str).length * 8; }
function drawTextC(ctx, str, cx, y, color) {
  drawText(ctx, str, Math.floor(cx - textW(str) / 2), y, color);
}
